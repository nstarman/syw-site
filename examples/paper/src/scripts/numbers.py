"""The paper's numbers, as \variable files in src/tex/output/."""

import numpy as np

import paths

helix = np.load(paths.data / "helix.npz")
xyz = helix["xyz"]
out = paths.tex / "output"
out.mkdir(exist_ok=True)
values = {
    "turns": f"{int(helix['turns'])}",
    "radius": f"{np.hypot(xyz[:, 0], xyz[:, 1]).mean():.2f}",
    "pitch": r"\qty{0.33}{\kpc}",
}
for name, value in values.items():
    (out / f"{name}.tex").write_text(f"% GENERATED by src/scripts/numbers.py\n{value}%")
